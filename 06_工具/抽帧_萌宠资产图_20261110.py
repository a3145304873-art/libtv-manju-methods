ok, fail = 0, []
for fname, subdir, shots in PLAN:
    src = SRC / fname
    if not src.exists():
        fail.append((subdir, '源文件缺失', fname))
        continue
    d = OUT / subdir
    d.mkdir(parents=True, exist_ok=True)
    for sec, desc in shots:
        out = d / f'{sec:03d}-{desc}.jpg'
        if out.exists():
            ok += 1
            continue
        r = subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-ss', str(sec),
                            '-i', str(src), '-vf', 'scale=640:-2', '-frames:v', '1',
                            '-q:v', '3', '-update', '1', str(out)],
                           capture_output=True)
        if out.exists() and out.stat().st_size > 5000:
            ok += 1
        else:
            fail.append((subdir, f'{sec}s {desc}', r.stderr.decode('utf-8', 'replace')[-80:]))

print(f'成功 {ok} 张')
