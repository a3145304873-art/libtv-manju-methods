def ensure_clauses(nodes):
    for n in nodes:
        if n["type"] != "gen-image":
            continue
        lab = n["meta"]["label"]
        for key, clauses in NEED.items():
            if ("%s" % key) in lab:
                mp = n["params"]["model_params"]
                pr = mp["prompt"]
                for c in clauses:
                    head = c.split("】")[0] + "】"
                    if head in pr:
                        continue
                    if "负向：" in pr:
                        pr = pr.replace("负向：", c + "\n" + "负向：", 1)
                    else:
                        pr = pr + "\n" + c
                mp["prompt"] = pr
                break

